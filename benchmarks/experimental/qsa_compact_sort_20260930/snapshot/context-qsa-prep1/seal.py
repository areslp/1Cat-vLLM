"""Seal only closed stable files; this process's output is not self-listed."""
import ast
import hashlib
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    os.umask(0o077)
    if (HERE / 'MANIFEST.json').exists():
        raise FileExistsError('source packet already frozen')
    files = []
    for path in sorted(HERE.rglob('*')):
        if path.is_symlink():
            raise ValueError('source symlink rejected')
        if path.is_file():
            if '__pycache__' in path.parts or path.suffix == '.pyc':
                raise ValueError('unregistered generated bytecode')
            raw = path.read_bytes()
            if path.suffix == '.py':
                ast.parse(raw, filename=str(path))
            files.append({'path': str(path.relative_to(HERE)), 'bytes': len(raw),
                          'sha256': hashlib.sha256(raw).hexdigest()})
    matrix = json.loads((HERE / 'matrix.frozen.json').read_text())
    cpu = json.loads((HERE / 'evidence/cpu-attempt2/RECEIPT.json').read_text())
    if cpu['status'] != 'PASS_LOCAL_CPU_NOT_SERVICE_OR_GPU':
        raise ValueError('targeted CPU batch did not pass')
    for name, expected in cpu['tested_source_sha256'].items():
        if hashlib.sha256((HERE / name).read_bytes()).hexdigest() != expected:
            raise ValueError('runtime/CPU-tested bytes changed after check')
    manifest = {'schema': 'CONTEXT_QSA_SOURCE_CPU_PACKET_V1', 'files': files,
                'bytes': sum(f['bytes'] for f in files),
                'dependencies': json.loads((HERE / 'DEPENDENCIES.json').read_text())['files'],
                'status': 'SOURCE_CPU_FROZEN_NOT_SERVICE_EXECUTED',
                'HTTP_requests': matrix['HTTP_requests'],
                'max_output_tokens': matrix['max_output_tokens'],
                'candidate_and_controller': 'PENDING_SEPARATE_REVIEW',
                'no_self_hash_or_transport_tail': True}
    raw = (json.dumps(manifest, sort_keys=True, indent=2) + '\n').encode()
    (HERE / 'MANIFEST.json').open('xb').write(raw)
    print(json.dumps({'manifest_sha256': hashlib.sha256(raw).hexdigest(),
                      'payload_files': len(files), 'payload_bytes': manifest['bytes'],
                      'matrix_sha256': hashlib.sha256((HERE / 'matrix.frozen.json').read_bytes()).hexdigest()}))


if __name__ == '__main__':
    main()
